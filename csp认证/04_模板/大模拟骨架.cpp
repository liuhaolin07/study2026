#include <bits/stdc++.h>
using namespace std;

using ll = long long;
#define all(x) (x).begin(), (x).end()
#define pb push_back
#define fi first
#define se second

// ============================================================================
// 第一步：拆规则 —— 读题 3 遍，把每条规则编号写在这里
// ============================================================================
// 【题意复述】用自己的话写一遍，写完对照样例验证理解是否正确
//
// 【规则清单】
//   R1: 输入 n 个事件，每个事件有 时间 t、优先级 p、编号 id
//   R2: 事件按时间升序处理
//   R3: 时间相同时，优先级高的先处理
//   R4: 时间和优先级都相同时，按输入顺序处理          <-- ⚠️ 最容易被漏掉的一条
//   R5: 处理一个事件时，若当前"容量"不足则跳过并记录，否则扣减容量
//   R6: 容量会在每个整点时刻自动恢复 k 点，但不超过上限 C
//
// 【限定词圈注】"同时"、"不超过"、"若…则"、"保证"
//   -> R3/R4 就是典型的"同时发生怎么处理"，CSP 大模拟最爱在这里设坑
//
// 【自造极端样例】
//   - n = 1                -> 检查最基本的流程
//   - 所有事件时间相同      -> 检查 R3/R4 的排序是否正确
//   - 容量始终为 0          -> 检查 R5 的跳过分支
//   - 容量一直满            -> 检查 R6 的上限裁剪
// ============================================================================

// ============================================================================
// 第二步：定状态 —— 先把所有需要维护的量列出来，再决定容器
// ============================================================================

// 事件：把"操作"抽象成统一的 struct，才能排序
// ⚠️ 一定要保留 idx（输入顺序），因为"同时刻按输入顺序"这类规则需要它
struct Event {
    ll t;      // 发生时间
    int p;     // 优先级
    int idx;   // 输入顺序（稳定排序的 tiebreaker）
    ll need;   // 本事件需要的容量
};

// 全局状态：所有会被修改的量集中放这里，不要散落在 main 里
struct State {
    ll capacity;                 // 当前容量
    ll last_refill_time;         // 上次恢复容量的时间点
    ll C;                        // 容量上限
    ll k;                        // 每个整点恢复量
    vector<int> served;          // 成功处理的事件编号
    vector<int> skipped;         // 被跳过的事件编号
};

State st;

// 多关键字排序比较器
// 原理：逐级比较，前一级相等才看下一级
// ⚠️ 致命易错点：最后一级必须用 <，绝对不能用 <=
//    sort 要求比较器满足"严格弱序"，相等时返回 true 会触发未定义行为，
//    数据量一大就直接 RE（运行错误），整题 0 分。这是 CSP 考场最惨烈的翻车方式。
bool cmp_event(const Event& a, const Event& b) {
    if (a.t != b.t) return a.t < b.t;        // R2: 时间升序
    if (a.p != b.p) return a.p > b.p;        // R3: 优先级降序
    return a.idx < b.idx;                    // R4: 输入顺序升序
}

// ============================================================================
// 第三步：排顺序 —— 明确事件的时间轴，以及"同时发生"怎么定序
// ============================================================================
// 上面的 cmp_event 就是这一步的产物。
// 如果规则更复杂（比如"某些事件可以打断正在处理的事件"），
// 就要改用 priority_queue 逐个取出，而不是一次性 sort。

// 容量恢复：处理事件前，先把从 last_refill_time 到 t 之间经过的整点补上
// 原理：不要一个一个整点循环（时间跨度大时会 TLE），直接算出经过了多少个整点
// ⚠️ 易错：整点计数是 (t - last) 还是 (t - last + 1)？取决于题意"整点时刻"是否含端点
//          拿不准就自己造一个 t=0 和 t=1 的例子手算验证
void refill_to(ll t) {
    if (t <= st.last_refill_time) return;
    ll steps = (t - st.last_refill_time + 99) / 100;   // 示例：每 100 单位时间恢复一次
    // ⚠️ 上面这行是示例逻辑，实际要按题意改。核心是"用除法代替循环"
    if (steps <= 0) return;

    // 先算会不会溢出：steps * k 可能超过 ll 范围，所以先和上限比较
    // ⚠️ 易错：直接 st.capacity += steps * st.k 再 min，中间那步就可能溢出
    if (steps >= (st.C - st.capacity + st.k - 1) / max(st.k, 1LL)) {
        st.capacity = st.C;                            // 一定到顶，直接赋值
    } else {
        st.capacity = min(st.C, st.capacity + steps * st.k);
    }
    st.last_refill_time = t;
}

// ============================================================================
// 第四步：分阶段实现 —— 每条规则单独一个函数，实现完就用样例验证
// ============================================================================

// R5: 处理单个事件
void process_event(const Event& e) {
    refill_to(e.t);                     // R6 先结算容量恢复
    if (st.capacity >= e.need) {        // R5 容量够 -> 处理
        st.capacity -= e.need;
        st.served.pb(e.idx);
    } else {                            // R5 容量不够 -> 跳过并记录
        st.skipped.pb(e.idx);
    }
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    // ---------- 读入 ----------
    int n;
    if (!(cin >> n)) return 0;          // 没有输入直接退出，避免本地空跑报错

    ll C, k;
    cin >> C >> k;
    st.capacity = C;                    // 初始容量按题意，这里是满的
    st.last_refill_time = 0;
    st.C = C;
    st.k = k;

    vector<Event> ev;
    ev.reserve(n);                      // 预分配，避免 push_back 反复扩容
    for (int i = 0; i < n; i++) {
        Event e;
        cin >> e.t >> e.p >> e.need;
        e.idx = i;                      // ⚠️ 别忘了记输入顺序
        ev.pb(e);
    }

    // ---------- 排序（第三步的成果）----------
    sort(all(ev), cmp_event);

    // ---------- 逐个处理（第四步）----------
    for (const auto& e : ev) process_event(e);

    // ---------- 输出 ----------
    // ⚠️ 输出格式必须逐字符对照样例：空格还是换行？结尾要不要换行？大小写？
    // ⚠️ 用 '\n' 不要用 endl
    cout << st.served.size() << '\n';
    for (size_t i = 0; i < st.served.size(); i++) {
        if (i) cout << ' ';
        cout << st.served[i] + 1;       // 示例：题目要求编号从 1 开始
    }
    cout << '\n';

    return 0;
}


/*
 * 文件名称：部分分暴力.cpp
 * 作    用：CSP 第 4/5 题的"薅部分分"暴力骨架合集，10 分钟内能抄改出一个能交的版本
 * 设计原理：CSP 按测试点给分，题面里"其中 30% 的数据满足 n <= 100"就是明示的送分点。
 *           与其在难题上死磕正解，不如先用最直白的暴力把 30~50 分锁进兜里。
 *           配合官方规则"多次提交取最高分、无罚分"，暴力提交是零风险的白拿分。
 * 易    错：暴力的第一原则是"直白到不可能写错"，不要边写边优化——
 *           写错了拿 0 分，写对了哪怕慢也有 30 分。
 *
 * 编译：g++ -O2 -std=c++17 -DONLINE_JUDGE -Wall 部分分暴力.cpp -o brute
 */

#include <bits/stdc++.h>
using namespace std;

using ll = long long;
#define all(x) (x).begin(), (x).end()
#define pb push_back
#define fi first
#define se second

const ll INF = 0x3f3f3f3f3f3f3f3fLL;

// ============================================================================
// 暴力 1：二进制枚举子集  —— 适用 n <= 20，"选或不选"型
// ============================================================================
// 原理：0 ~ 2^n-1 的每个整数对应一种选法，第 i 位为 1 表示选第 i 个
// 复杂度：O(2^n * n)
// ⚠️ 易错：n >= 31 时 1 << n 会溢出 int，必须写 1LL << n
// ⚠️ 易错：判断第 i 位要用 (S >> i) & 1，不要用 S & (1 << i) 再当 bool 用（值不是 0/1）
ll brute_subset(int n, const vector<ll>& w, ll limit) {
    ll best = 0;
    for (ll S = 0; S < (1LL << n); S++) {
        ll sum = 0;
        bool ok = true;
        for (int i = 0; i < n; i++) {
            if ((S >> i) & 1) {
                sum += w[i];
                if (sum > limit) { ok = false; break; }   // 提前剪枝，能快很多
            }
        }
        if (ok) best = max(best, sum);
    }
    return best;
}

// ============================================================================
// 暴力 2：全排列枚举  —— 适用 n <= 10，"求顺序"型
// ============================================================================
// 原理：next_permutation 依次生成所有排列
// 复杂度：O(n! * n)
// ⚠️ 易错：调用前必须先 sort，否则只会生成"字典序大于当前序列"的那部分排列
ll brute_permutation(vector<int> p) {
    sort(all(p));
    ll best = INF;
    do {
        ll cost = 0;
        for (size_t i = 0; i + 1 < p.size(); i++) cost += abs(p[i + 1] - p[i]);
        best = min(best, cost);
    } while (next_permutation(all(p)));
    return best;
}

// ============================================================================
// 暴力 3：区间操作直接模拟  —— 适用 n, q <= 5000，"区间改 + 区间查"型
// ============================================================================
// 原理：不用线段树/树状数组，每次操作老老实实扫一遍
// 复杂度：O(n * q)
// ⚠️ 易错：n,q 到 1e5 时这是 1e10，必 TLE，只能拿小数据分——但那正是我们要的
// ⚠️ 易错：求和一律 long long
struct BruteArray {
    vector<ll> a;
    explicit BruteArray(int n) : a(n + 1, 0) {}

    void update(int l, int r, ll v) {              // 区间加
        for (int i = l; i <= r; i++) a[i] += v;
    }
    ll query(int l, int r) const {                 // 区间和
        ll s = 0;
        for (int i = l; i <= r; i++) s += a[i];
        return s;
    }
};

// ============================================================================
// 暴力 4：Floyd 全源最短路  —— 适用 n <= 400，"图上多组询问"型
// ============================================================================
// 原理：三重循环，k 必须在最外层
// 复杂度：O(n^3)
// ⚠️ 易错：k 循环放最里面结果是错的，这是 Floyd 唯一但致命的坑
// ⚠️ 易错：初始化要用 INF，且 INF + INF 不能溢出（所以用 0x3f... 这种小一点的值）
vector<vector<ll>> brute_floyd(int n, const vector<vector<ll>>& g) {
    vector<vector<ll>> d = g;
    for (int k = 0; k < n; k++)
        for (int i = 0; i < n; i++)
            for (int j = 0; j < n; j++)
                if (d[i][k] < INF && d[k][j] < INF)
                    d[i][j] = min(d[i][j], d[i][k] + d[k][j]);
    return d;
}

// ============================================================================
// 暴力 5：DFS 直接数方案  —— 适用 n <= 20，"计数"型
// ============================================================================
// 原理：把搜索树走一遍，到叶子就 +1
// 复杂度：指数级，但小数据够用
// ⚠️ 易错：忘记标记 visited 会死循环；回溯时忘记撤销标记会漏解
ll brute_count;
void brute_dfs(int u, int n, vector<bool>& vis, const vector<vector<int>>& g) {
    if (u == n - 1) { brute_count++; return; }     // 到达终点，方案数 +1
    vis[u] = true;
    for (int v : g[u]) {
        if (!vis[v]) brute_dfs(v, n, vis, g);
    }
    vis[u] = false;                                 // ⚠️ 回溯必须撤销
}

// ============================================================================
// 暴力 6：完全没思路时的保底写法
// ============================================================================
// 目标不是做对，是"别交白卷"。以下三招按顺序试：
//   (a) 特判 n == 1、n == 2 这些小情况，手算出答案直接输出
//   (b) 如果题目问"最大值/最小值"，输出一个显然的界（如所有元素之和、0）
//   (c) 把样例的输入输出硬编码进去（能过样例点，通常 5~15 分）
// ⚠️ (c) 只在真的一点思路都没有时用；能写暴力就写暴力，别硬编码
ll brute_fallback(int n, const vector<ll>& a) {
    if (n == 0) return 0;
    if (n == 1) return a[0];
    ll mx = *max_element(all(a));
    ll mn = *min_element(all(a));
    return mx - mn;                                 // 示例：随便一个"看起来合理"的答案
}

// ============================================================================
// 核心套路：分层派发  —— 考场上最重要的写法
// ============================================================================
// 原理：按数据范围分成几档，小数据走暴力（保证拿分），大数据走正解（冲满分）
// 好处：即使正解写到一半没时间了，把暴力分支留下来照样能交，稳拿 30~50 分
// ⚠️ 易错：三个分支的函数签名要一致，否则切换时改起来容易出错
// ⚠️ 易错：写完正解后一定要回头测一遍暴力分支还对不对（改代码时容易改坏）
ll solve_brute(int n, const vector<ll>& a) { return brute_subset(n, a, INF / 2); }
ll solve_quadratic(int n, const vector<ll>& a) {
    ll best = 0;                                    // O(n^2) 版本
    for (int i = 0; i < n; i++) {
        ll s = 0;
        for (int j = i; j < n; j++) { s += a[j]; best = max(best, s); }
    }
    return best;
}
ll solve_optimal(int n, const vector<ll>& a) {
    // 正解写在这里。写不完就先把这个函数体留成 return solve_quadratic(n, a);
    return solve_quadratic(n, a);
}

ll solve_dispatch(int n, const vector<ll>& a) {
    if (n <= 20)        return solve_brute(n, a);
    else if (n <= 5000) return solve_quadratic(n, a);
    else                return solve_optimal(n, a);
}

